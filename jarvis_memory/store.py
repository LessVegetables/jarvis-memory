"""
Доступ к данным о пользователях.

СЕЙЧАС: захардкоженные словари, чтобы модуль можно было отдать оркестратору
уже сегодня и он не ждал базу.

ШАГ 2 плана: то же самое, но из SQLite (jarvis.db). Сигнатуры функций ниже
меняться не будут — поменяется только их содержимое. Поэтому app.py,
написанный против этих функций сегодня, продолжит работать после перехода
на настоящую базу.
"""

from __future__ import annotations

from datetime import date

# --- временные данные (ШАГ 2 заменит это на таблицы SQLite) ------------------

_PROFILES = {
    "anton": {"name": "Антон", "age": 21},
    "masha": {"name": "Маша", "age": 19},
}

# (weekday, time, title) — weekday как в date.weekday(): 0 = понедельник
_SCHEDULE = {
    "anton": [
        (0, "16:00", "Лекция по матанализу, ауд. 305"),
        (0, "19:30", "Тренировка"),
        (1, "10:00", "Лабораторная по физике"),
    ],
    "masha": [
        (0, "09:00", "Английский"),
        (0, "14:00", "Встреча с научруком"),
        (2, "18:00", "Репетиция"),
    ],
}

_FACTS = {
    "anton": ["Вегетарианец", "Аллергия на орехи", "Собаку зовут Бобик"],
    "masha": ["Не пьёт кофе после обеда", "Учится на втором курсе"],
}


# --- публичные функции (их сигнатуры — это и есть контракт) ------------------

def get_profile(user_id: str) -> dict | None:
    """Профиль пользователя или None, если такого user_id нет."""
    return _PROFILES.get(user_id)


def get_schedule(user_id: str, day: date) -> list[tuple[str, str]]:
    """События пользователя на указанный день: [(время, описание), ...].

    Это обычная выборка по ключу, а не поиск по смыслу. Расписание имеет
    жёсткую структуру, поэтому здесь не нужен (и вреден) RAG: SQL-запрос
    либо вернёт верный день, либо ничего — он не может "почти угадать".
    """
    rows = _SCHEDULE.get(user_id, [])
    return [(time, title) for weekday, time, title in rows if weekday == day.weekday()]


def get_facts(user_id: str, transcript: str, limit: int = 3) -> list[str]:
    """Факты о пользователе, релевантные вопросу.

    СЕЙЧАС: возвращает первые `limit` фактов, вопрос игнорируется.
    ШАГ 5 плана: здесь появится векторный поиск (sqlite-vec + эмбеддинги),
    и `transcript` начнёт влиять на выдачу. Аргумент добавлен уже сейчас,
    чтобы потом не менять вызывающий код.
    """
    return _FACTS.get(user_id, [])[:limit]
